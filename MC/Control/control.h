/* ==================== 设备参数 ==================== */
#define MOTOR_POLE_PAIRS   7u   /* 电机极对数（位置传感器初始化使用），按实际电机修改 */

/* ==================== 分频调度参数（20kHz 时基） ==================== */
#define CONTROL_HIGH_HZ 20000u    /* 高频频率（Hz）：ADC 注入中断 = 20kHz */
#define CONTROL_MID_DIV   2u     /* 中频分频：20kHz / 2 = 10kHz */
#define CONTROL_LOW_DIV   4u     /* 低频分频：20kHz / 4 = 5kHz */
#define CONTROL_MID_HZ 10000u    /* 中频频率（Hz）：位置/角度/速度更新频率 */

/* ==================== 编码器校准：方式一 · 两点锁轴法 ====================
 * 点 0：矢量锁电角度 0°（Uα=U，A 相磁轴）→ 定零点
 * 点 1：矢量锁电角度 +90°（Uβ=U）      → 与点 0 的机械位移定方向
 * 下面都是标定用参数/判据阈值，按电机与机械情况调整即可（改这里，不用进 control.c）
 * ⚠ 已知短板：锁轴只采到**一个**转子位置，该处"电磁对齐转矩 vs 齿槽/静摩擦"的平衡误差
 *   直接进 offset，而每次上电转子落点随机 ⇒ 零位残余 3~5° 电角度（见下 LOCK_VOLT 注释）。
 *   方式二（慢速旋转）就是为消掉它而做的，见本节末尾"方式选择"。
 * ==================================================================== */
#define ENC_CALIB_LOCK_VOLT   0.30f      /* 锁轴电压（调制比）：0.30×6V=1.8V → @R=3.5Ω ≈0.51A（额定）
                                            ⚠ 这个值决定**每次上电零位的重复性**，不只是"够不够拉动"：
                                            锁轴是把转子拉到电角度 0°，但转子最终停在哪取决于
                                            电磁对齐转矩 vs 齿槽/静摩擦：
                                              0.15(9.2mN·m) → 残余偏差 6~9° 电角度
                                              0.30(18.4mN·m) → 残余偏差 3~5° 电角度  ← 现用
                                            而 12 槽 14 极电机的齿槽周期是 30° 电角度，
                                            每次上电转子初始位置落在其中任意处 → 零位偏差随机。
                                            偏差 δ 直接吃顶速（|u|·cosδ）：δ=10° → 2539、δ=15° → 2490
                                            —— 这就是"有时 2600、重启后达不到"的原因。
                                             ✓已实现根治手段：改用**方式二 慢速旋转标定**
                                               （见本节末尾 ENC_ROT_*：匀整圈 + 正反双向平均，
                                                齿槽误差与跟随负载角都被消掉）
                                             （校准结果掉电保持 = 后续开发内容） */
#define ENC_CALIB_MIN_SETTLE (CONTROL_HIGH_HZ / 10u)  /* 最小锁轴等待：100ms（先收敛再判稳定） */
#define ENC_CALIB_STABLE_ERR 0.00175f    /* 稳定判据：位置波动 < 0.1° 机械（rad） */
#define ENC_CALIB_MAX_SETTLE (CONTROL_HIGH_HZ * 1u)   /* 锁轴最长等待：1s（超时强制读数兜底） */
#define ENC_CALIB_READ_N     (CONTROL_HIGH_HZ / 20u)  /* 读数平均拍数：50ms = 1000 拍 */

/* 方向判据容差（相对第二点理论位移 π/2/极对数）：
   点 0 锁电角度 0°、点 1 锁电角度 +90°，转子标称机械位移 Δ = π/2/极对数 ≈ 0.224rad（12.9°）；
   两个锁轴点都到位时 Δ 应当正好是 1.0 倍（转子跑过头只会更大、卡住只会更小）：
     < 0.25 倍 → 转子基本没动，符号是噪声 → 按 +1 兜底 + suspect
     > 1.5 倍 → 转子走了远路（往往说明点 0 根本没锁到位，偏移也不可信）→ suspect
   落在窗口内才认位移符号为方向 */
#define ENC_CALIB_DIR_MIN_RATIO  0.25f
#define ENC_CALIB_DIR_MAX_RATIO  1.50f

/* 方向判据手动强制（调试用）：0 = 由两点锁轴自动判方向；+1/-1 = 强制该方向、跳过自动判据
   ——用来 A/B 验证自动判据：先看 CAL 行打印的 dir 与 dmech，再改成相反值烧一次，
      哪种能转就说明哪种是对的（dir 对但电机仍不转 → 问题不在方向，见 user.c 测试块注释） */
#define ENC_CALIB_DIR_FORCE      0

/* ==================== 编码器校准：方式选择 ====================
 * 常量 ENC_CALIB_METHOD_2POINT / _ROT 定义在 Algorithm/mc_enc_calib.h（算法的对外接口），
 * 本节的 ENC_ROT_* 是喂给它的参数；control.c 里把它们折成 EncCalib_Cfg_t。
 * 两种方式产出完全相同的东西（写 PosSensor 的 elec_dir + elec_offset、上报 CAL 行），
 * 差别只在"怎么量"：
 *   · 方式一 两点锁轴：快（0.3~2s），但零位残余 3~5° 电角度随机（只采一个位置，齿槽误差直接进）
 *   · 方式二 慢速旋转：约 3s，把齿槽误差沿整圈平均掉 + 正反双向差分消掉跟随负载角
 *                     ⇒ 零位残余可望 <1°，并额外产出"跟随负载角"与"齿槽纹波幅度"两个观测量
 * 换方法只改这一行（两种实现都在 mc_enc_calib.c 里，随时切回）
 * ==================================================================== */
#define ENC_CALIB_METHOD          ENC_CALIB_METHOD_ROT   /* ← 校准方式：默认慢速旋转 */

/* ==================== 编码器校准：方式二 · 慢速旋转标定 ====================
 * 做法：按固定电频率给一个旋转电压矢量（开环拖转，像步进电机的软启动），转子同步跟随后：
 *   ⚠ 矢量压在**指令 d 轴**上（ud=rot_volt、uq=0）—— 用 (0,V) 会让转子 d 轴多跑 90°，
 *     算出的 offset 整整小 90°，表现为"CAL 行正常但电机不转、一直有电流"（详见 mc_enc_calib.c）
 *   ① 每拍算 e = θe_cmd − dir·pp·θm —— 它就是 offset 加上"跟随负载角 δe"；
 *      沿整圈（每次机械圈含 LCM(12,14)=84 个齿槽周期）取平均 ⇒ 齿槽误差被抹平；
 *   ② 正向 e_fwd = offset + δe、反向 e_rev = offset − δe ⇒ **圆平均**即得 offset，
 *      且 δe = (e_fwd − e_rev)/2 被顺手读出来（这就是"能差分就差分"）。
 * 为什么必须正反两个方向：单向旋转时转子要落后磁场一个 δe 才出得来克服摩擦的转矩，
 *   这个 δe 会**整份**混进 offset（8Hz、0.30 调制比下约 3~6° 电角度，正好和要消掉的齿槽
 *   误差同量级）——只转一个方向等于没治好。
 * 判据（都随 CAL 行打印）：
 *   · rF/rR = 正/反向的跟随性比值 |Δθm|·pp/|Δθe|，同步时应 ≈1.000
 *     ⚠ 失步是**按极对数量子化**的：丢一步 = 360° 电角度 = 测量窗(2520°)的 **14.3%**
 *       ⇒ 丢一步时 ratio = 0.857，而 offset 的偏差 ≈ 滑移量的一半 ≈ 180° 电角度
 *       （结果彻底不可用）。所以接受窗口必须远小于 14.3%（现在取 ±2%），
 *       **早期用 0.80~1.20 是错的：丢一步会被判成 ok**（这正是"有时行有时不行"的根因之一）。
 *       它同时也复核极对数：pp 填错会按比例偏离 1
 *   · resid = e 的峰峰值 = 齿槽造成的**转子位置偏差**幅度（电角度）。
 *     ✓本机实测 **19.5°**（p-p）：在周期误差上随机取一点、期望偏差 ≈ p-p/4 ≈ 4.9°，
 *       正好对上笔记里两点锁轴"零位残余 3~5° 且每次上电随机" ✓ —— 也就是说
 *       那 3~5° 的根子就是它；旋转标定取的是**整圈平均**，所以把这一项抹掉了
 *   · load = δe（电角度）：两方向差的一半，超限 ⇒ 负载角异常/没同步 ⇒ SUSPECT。
 *     ✓本机实测 8.4° @8Hz/0.40 调制比 ⇒ 低速（≈69rpm）平均负载转矩
 *       = Kt·I·sinδe ≈ 3.3 mN·m（含齿槽峰值）；比 1000rpm 的净摩擦 1.18mN·m 大 ~3 倍，
 *       符合"低速负载由齿槽主导"的预期
 *   · att = 第几次尝试：判据没过会自动整段重试（丢步/换向冲击都是暂态）
 * ✓验收记录（已通过）：
 *   ① 90° 约定坑修复前后 off 恰好跳 270.02°（= −90°）：4.9973 → 0.2853 rad，
 *      而修复前预测的修复后值是 0.2848（命中，差 0.03°）⇒ 说明"拖转矢量必须压在
 *      指令 d 轴上"这条推理成立；修复后**电机正常转动**（修复前只有电流、无转矩）
 *   ② 重复性：三次上电 off 相互差 ≤0.0011 rad = **0.06° 电角度**
 *      （两点锁轴是 3~5° 随机）⇒ 提升约两个数量级，这正是本方法的目标
 *   ③ resid 19.52/19.17°、load 8.40/8.56° 两次上电几乎一致 ⇒ 观测量本身也可重复
 *   （推论：速度环 1000rpm 下 ch9/Ud 残差应从原来的 −0.027 掉到 ≈0.000）
 * 稳定性（"有时失败"的另一个根因）：
 *   · 上电时转子停在任意位置，一给矢量就有一次吸附冲击（本机磁井谐振约 31.5Hz、阻尼小），
 *     若不等它衰减就启转，容易丢步 ⇒ 现在 ALIGN 段用**滑动窗**判"最近 W 拍没动"才启转；
 *   · 正→反换向也走一次 ALIGN（软停到 0 再反向），避免直接穿越时的换向冲击；
 *   · 判据没过自动重试 ENC_ROT_RETRY_N 次。
 * 时间账（当前参数）：每方向 = ALIGN(软停 0.15 + 判定 ≥0.10，最长 1.15) + PRE(0.15+0.25)
 *   + MEAS(0.875) ⇒ 典型 **≈3.0s**、最慢 ≈4.9s（最慢只发生在 align 一直判不出静止时）；
 *   每触发一次重试再 +≈3.0s（上限见 ENC_ROT_RETRY_N ⇒ 最坏上电约 9.7s，那是真出故障了）
 * 热账：全程 ≈0.64A（2.4V/3.5Ω 减去一点反电动势）；比额定的 0.5A 高但远低于保底 0.9A，
 *   一次性几秒，可接受；这个余量是**为了顶过齿槽**（电压给太小会丢步）
 * ==================================================================== */
#define ENC_ROT_VOLT         0.30f      /* 旋转矢量幅值（调制比）：@R=3.5Ω ≈0.51A（与锁轴同值，历史验证值）
                                           ⚠ 两个方向的取舍：
                                             · 给大了（0.40 ⇒ 0.69A）：顶齿槽余量足、不易丢步，
                                               但**驱动器电流负担大**——实测出现过 DRV8311 nFAULT
                                               （输出级关断 ⇒ 转子根本不动 ⇒ 校准报 driver-fault）
                                             · 给小了（<0.25）：电流小，但 δe 变大、丢步风险高
                                           当前取回 0.30（18.4mN·m，仍是拖动所需 ~3mN·m 的 6 倍）；
                                           若 CAL 行频繁出现 first=slip 再往上加，若有 nFAULT 就往下调 */
#define ENC_ROT_FREQ_HZ      8.0f       /* 电频率（Hz）：机械转速 = 8/7 ≈1.14rev/s ≈69rpm（很慢）
                                           （J=3e-6，加速力矩 J·α 可忽略 ⇒ 唯一要求是"别丢掉同步"） */
#define ENC_ROT_RAMP_S       0.15f      /* 升/降速时间（s）：软启动、软停车、软换向都用它
                                           （不升速直接给 8Hz 会有一次拖拽冲击） */
#define ENC_ROT_SETTLE_S     0.25f      /* 升速后稳定时间（s）：这段只跟踪不测量，避开起动暂态 */
#define ENC_ROT_ALIGN_MIN_S  0.10f      /* ALIGN 段最小等待（s）：软停完成后至少等这么久才判"静止" */
#define ENC_ROT_ALIGN_MAX_S  1.00f      /* ALIGN 段最长等待（s）：超时 ⇒ CAL 行报 align-not-settled
                                           （机械卡/编码器不更新会走到这里），但仍继续跑完 */
#define ENC_ROT_WIN_S        0.05f      /* "静止"判据的滑动窗长度（s）：与 50ms 前的角比较
                                           ⚠ 必须用滑动窗：转子吸附冲击本身就是几十度位移，
                                             用"从段首累计"的 min/max 判据永远不成立（方式一就是这样） */
#define ENC_ROT_REVS         1.0f       /* 每方向测量的**机械**圈数（1 圈 = 84 个齿槽周期） */
#define ENC_ROT_MAX_MEAS_S   2.0f       /* 测量段超时（s）：到点还没走够圈数 ⇒ 报 no-travel/timeout */
#define ENC_ROT_RATIO_MIN    0.98f      /* 跟随性比值下限：丢一步 = 0.857 ⇒ ±2% 一定能抓住 */
#define ENC_ROT_RATIO_MAX    1.02f      /* 跟随性比值上限（噪声只贡献 ±0.01%，余量足够） */
#define ENC_ROT_MAX_LOAD_DEG 20.0f      /* 跟随负载角 δe 上限（电角度）：超限 ⇒ 没同步/摩擦过大 */
#define ENC_ROT_RETRY_N      1         /* 判据没过时自动整段重来的次数（0 = 不重试）
                                           （暂态丢步重来一次大多就过；每重试一次 +≈3.0s，
                                             上限 1 是为了把最坏上电时间压在 ~10s 内） */

/* ==================== 驱动器故障（nFAULT）处理 ====================
 * DRV8311 报故障时输出级直接关断：没有电流就没有转矩 ⇒ 校准不可能成功
 * （现象是"转子纹丝不动、dm=0"，会被误判成丢步而白跑重试）。
 * 处理策略（既不能硬跑，也不能一故障就永久放弃——故障可能是暂态的）：
 *   · nFAULT 期间：关断输出、**不推进校准**，只累计等待时间
 *   · 故障消失：复位校准状态机、从整段开头重来（故障期间转子可能被动过）
 *   · 累计等待超过 DRV_FAULT_WAIT_S 仍不恢复 ⇒ 判 ENC_FAIL_DRV 收尾
 *     （CAL 行报 driver-fault；不写 offset、不置 enc_calib_done ⇒ 测试模式继续被拦）
 * ==================================================================== */
#define DRV_FAULT_WAIT_S     2.0f      /* 允许驱动器故障持续多久（累计）后放弃 */

/* ==================== 电机电气参数（电流环增益/前馈的推导基础） ====================
 * 这些是**物理参数**，量出来按需改；电流环增益由它们算出来（见下节），不手调：
 *   R     相电阻（Ω）  ：万用表量线-线电阻 ÷2
 *   L     相电感（H）  ：LCR 表量线-线电感 ÷2（表贴式 Ld≈Lq）
 *   ψf    永磁磁链（Wb）：由反电动势常数折算 ψf = Ke[V·s/rad(电)] = 60/(2π·Kv[rpm/V]·极对数)
 *   Udc   母线电压（V）：目前**未测量**（V_Bus 通道没读），先按额定值填；
 *                       填错只影响"伏特→调制比"换算与增益绝对值，不影响逻辑；
 *                       闭环已反推 ≈12.1V（由 1000rpm 的 ch10 反算，见 docs 笔记 2.8），
 *                       但该式里 Udc 与 ψf 是 **1:1** 的 ⇒ 两者分不开，只能算旁证
 * ============================================================================ */
#define MOTOR_UDC_NOMINAL   12.0f       /* 母线电压额定（V） */
#define MOTOR_R_PHASE        3.5f       /* 相电阻（Ω）= 线-线电阻÷2
                                           ✓实测（母线 VM 实测 12V、夹死轴）：
                                             Iq=0.508 → Uq=0.292；Iq=0.502 → Uq=0.300
                                             ⇒ R = Uq×(Udc/2)/Iq = 3.45~3.59Ω，取 3.5Ω
                                           （之前的 4.2Ω 按"14V"折算，而那一轮板子实际只吃到
                                             ~11.7V：用 14V 会把 2300rpm 预测成 2770，用 11.7V 才得 2293 ✓）*/
#define MOTOR_LD         0.00140f       /* d 轴电感（H）= 1.4mH：规格书"绕线电感 2.8mH"是**端子间**电感
                                           （第三相悬空）L_LL = 2(L_self−M)，dq 模型用的是
                                           Ldq = L_self−M = L_LL/2 = 1.4mH；
                                           规格书另一个"相电感 Ls=0.86mH"是每相自感，
                                           按 M=−Ls/2 推 Ldq=1.5×0.86=1.29mH，两法差 9% ✓ 互相印证
                                           ⚠ 别直接把 2.8mH 或 0.86mH 填进来（会差 2 倍/1.6 倍） */
#define MOTOR_LQ         0.00140f       /* q 轴电感（H）：表贴式 Ld≈Lq */
#define MOTOR_FLUX       0.00340f       /* 永磁磁链 ψf（Wb）→ Kv≈400rpm/V：✓由顶速数据反推
                                           顶速时实测 Ud=−0.239 调制比(=1.43V) 正是"角度滞后 δ≈14°
                                           时 d 轴需要的补偿电压" ωe·ψf·sinδ ⇒ ψf≈1.43/(1718·0.242)
                                           =0.00344；夹死/空载多种反推落在 0.0030~0.0037，取 0.0034
                                           ✓第三个独立测点（跨度很大）：1000rpm 闭环由 ch10 反算
                                             0.00337（见 docs 笔记 2.8）；
                                           想更准：断开驱动器、用手/电钻匀速转轴，读 CSV 的 ch2(rpm)
                                           并用万用表量线-线电压(RMS)：
                                             ψf = 0.8165·V_LL_rms/ωe ， ωe = rpm/60·2π·7
                                           （Kv≈400 时 1000rpm 对应约 3.1V RMS，好量）*/

/* ==================== 电流环参数 ====================
 * 增益按"目标带宽 + 电气参数"算，不拍脑袋（推导见 mc_current.h）：
 *     ωc = 2π·CURRENT_BW_HZ                        （rad/s）
 *     kp = L·ωc / (Udc/2)   [调制比/A]             （PI 零点对消电气极点 R/L）
 *     ki = R·ωc / (Udc/2)   [调制比/(A·s)]         （内部乘 dt，与控制频率无关）
 * 例（当前实测值）：R=3.5Ω、L=1.4mH、Udc=12V、带宽 400Hz
 *     → kp ≈ 0.586 调制比/A，ki ≈ 1466 调制比/(A·s)
 *     → PI 零点 ki/kp = 2500 rad/s 正好对上电机电气极点 R/L = 2500 rad/s（零极点对消 ✓）
 * 带宽越慢越稳；参数都量准后可以提到 400~800Hz（20kHz 采样下延迟约 (1~1.5)·Ts，
 * 400Hz 只吃掉 ~10° 相位裕度）。有振铃就先把带宽降一半。
 * 也可以运行中直接改 mc.current.kp / ki 现场试。
 * ==================================================================== */
#define CURRENT_BW_HZ     400.0f        /* 目标电流环带宽（Hz）：参数已实测，按设计值 400 */
#define CURRENT_U_MAX      1.10f        /* dq 电压矢量幅值上限（调制比）
                                           1.0 = Udc/2（相电压峰值），SVPWM 线性区上限 2/√3≈1.1547。
                                           旧值 0.95 把 12V 空载顶速压到 ~1950rpm；1.10 → ~2280rpm
                                           （实测 2245/2288 ✓）。限幅判据已改用精确近似
                                           （VecMag 0.96/0.40，误差 <4%）：此前 max+0.5·min 在斜方向
                                           高估 11.8%，顶速矢量真实幅值只有 1.008 却判成顶到 1.10
                                           ——修掉后顶速预计提到 ~2530-2610rpm，✓实测 **2578rpm**
                                           （即规格书 2600 的 99.2%，见 docs 笔记 E7）。
                                           再往上受**电流采样**限制：低边分流需要开关后的建立时间
                                           （真实 |u|≈1.10 时最大占空比 ~0.976，波峰前 0.6us ✓），
                                           ⚠ 必须配合 drv8311_cur.c 把 ADC 触发点改到计数器
                                             波峰（否则调制比 >1.04 时相电流读数会被采样时刻污染）*/
/* ==================== 电流限幅：两道（用户限幅 + 保底限幅） ====================
 *  用户限幅  mc.target.iq_max      ：速度/位置模式的 Iq 给定上限（＝转矩限幅）。
 *                                    用户/上位机指定，上电默认 = CURRENT_I_MAX_USER。
 *  保底限幅  CURRENT_I_MAX_GUARD   ：硬件保护上限，**编译期常量、运行中不可改**。
 *  实际生效限幅 = min(用户限幅, 保底限幅)，由速度环每拍计算（见 mc_speed.c），
 *  电流环再对任何来源的给定做一次逐轴保底限幅（防绕过：直接写字段也顶不破）。
 *  过流保护 CURRENT_I_TRIP 在两者之上，是最后的事后兜底（latch，需重新上电）。
 *  不变量：CURRENT_I_MAX_USER ≤ CURRENT_I_MAX_GUARD < CURRENT_I_TRIP
 * ============================================================================ */
#define CURRENT_I_MAX_USER   0.5f       /* 用户限幅默认值（A）= 额定电流：上电写进 target.iq_max */
#define CURRENT_I_MAX_GUARD  0.9f       /* 保底限幅（A）：必须明显低于 CURRENT_I_TRIP(1.2A) */
#define CURRENT_FF_EN         0         /* 1 = 使能前馈解耦：R/L/ψf 都已实测，可试开
                                           （高速时前馈顶掉反电动势 ωe·ψf，PI 只需补 R·i） */
#define CURRENT_I_TRIP      1.2f        /* 软件过流阈值（A，矢量幅值）：额定 0.5A
                                           （R=3.5Ω 实测：满调制堵转 I = u_max·(Udc/2)/R
                                             = 1.10×6/3.5 = 1.89A@12V（14V 下 2.20A），
                                             阈值必须低于它才兜得住"符号反了跑飞"；
                                             1.2A=2.4×额定，不会误伤 0.5A 正常阶跃）*/
#define CURRENT_I_TRIP_N     3u         /* 连续超阈值拍数（3 拍 = 0.15ms）才锁定：电流上升很快
                                           （τ=L/R，符号反时 0.2ms 就能到安培级），
                                           去抖不能太久；噪声要连续 3 拍 >1.2A 基本不可能 */

/* ==================== 速度环参数 ====================
 * 级联：速度环（外环，10kHz，输出 Iq 给定）→ 电流环（内环，20kHz）。
 * 增益按"目标带宽 + 转动惯量"算（推导见 mc_speed.h），不手调：
 *     Kt   = 1.5·极对数·ψf          [N·m/A]   电磁转矩常数（1.5 来自幅值不变 Clarke/Park）
 *     ωsc  = 2π·SPEED_BW_HZ         [rad/s]   目标带宽
 *     kp   = J·ωsc/Kt               [A/(rad/s)] → 换算成 A/rpm 再乘 (2π/60)
 *     ki   = kp·ωsc/4               [A/(rad·s)] 零点放 ωsc/4（相位裕度 ≈76°）
 * 带宽上限由**反馈滤波**决定，不是算出来的 kp：mech_speed_filt 是 fc≈95Hz 的一阶低通
 * （pos_sensor.c），它在 95Hz 处已经吃掉 45° 相位 → 本环带宽取 20~40Hz 才有裕度。
 * J（转子+负载转动惯量）已按**实测反推值**填入（见 MOTOR_INERTIA），增益不再是"估错 7 倍"：
 * 当前实际生效 kp ≈ 5.53e-4 A/rpm、ki ≈ 8.69e-3 A/(rpm·s)（上电 CFG2 行会打印核对）。
 * 仍需现场重算的场合：负载变了（换云台/加配重）→ kp ∝ J 跟着变，方法见 user.c 测试块注释。
 * ⚠ 已知限制（后续可做）：反馈只有"最新值"，没有新鲜度看门狗——
 *   若编码器中途失效，mech_speed_filt 会冻结在最后的值，速度环会一直加力矩到
 *   iq_max（电流过流保护不会触发，因为 0.5A < CURRENT_I_TRIP）。真要做安全版，
 *   需要在 BSP/设备层加"连续 N 拍没有有效新帧 → 置失效"的看门狗，速度环据其回零。
 * ==================================================================== */
#define MOTOR_INERTIA        3.0e-6f    /* 转子+负载转动惯量 (kg·m²)：**实测反推值 ≈3e-6**，
                                          不再用早期估的 2e-5（偏大 ~7 倍，正是 30Hz 版恒幅振荡的
                                          根因：J 估大 → 同一个"10Hz 标签"实际交越 119.5Hz、PM 11.8°）。
                                          ★实测（斜坡段 ch15）：目标 1000rpm、斜坡 3000rpm/s 时
                                          iq_ref ≈ 0.0618A；闭环仿真 J=3e-6 给 0.0617A
                                          （J=2e-5 会给 0.2096A）。
                                          精确定值：J = (iq_斜坡 − iq_稳态)·Kt/314
                                          ✓闭环实测复核（J=3e-6 这版固件，1000rpm）：斜坡段
                                          ch15 = 0.061A、稳态（=摩擦电流，原 ?待测）= 0.033A
                                          ⇒ J = (0.061−0.033)×0.0357/314 = 3.18e-6，与填入值差 6%
                                            （差值 = 斜坡段平均转速的摩擦 ≠ 1000rpm 的摩擦，
                                             落在 1.6mA 电流分辨率量级内 ⇒ 暂不再调 MOTOR_INERTIA）
                                          ⚠ kp ∝ J：换负载/加配重后必须重测，否则带宽标签失真 */
#define SPEED_BW_HZ          10.0f      /* 目标速度环带宽（Hz）：改正 J 之后的**保守起点**
                                           （J=3e-6 时 kp=5.53e-4、ki=8.69e-3，CFG2 行可核对）。
                                           历史：早期 J 估成 2e-5 时，"30Hz"实际给的是 kp=0.01106
                                           → 真实交越 119.5Hz、PM 11.8° → 实测恒幅振荡
                                           （1000rpm 下 rpm 在 896~1100 之间摆，±10%）。
                                           ⚠ "10Hz"只是设计标签：真实交越还与 J、Kt、95Hz 反馈滤波
                                           有关，判据一律以实测为准：
                                             · 仍振荡（~20Hz 以上嗡嗡声）→ 继续降到 6Hz
                                             · 稳但偏软、静差恢复慢 → 往上加（15 → 20 → 25）
                                             · 振荡周期长（0.2~1s 的"喘振"）→ ki 偏强：
                                               保持 kp，调 SPEED_KI_RATIO 减小 ki
                                           带宽上限仍受 95Hz 反馈滤波限制，别超过 30~40；
                                           要看 20~30Hz 振荡需临时把 PRINT_PERIOD_MS 改成 10 */
#define SPEED_KI_RATIO       0.25f      /* PI 零点位置：ki = kp·ωsc·SPEED_KI_RATIO（0.25 → 零点在
                                           ωsc/4，相位裕度 ≈76°）。
                                           **诊断用**：置 0 = 纯比例 → 振荡消失说明是 ki 偏强，
                                           仍振荡说明是 kp/延迟问题（两者对策完全不同） */
#define SPEED_REF_RAMP_RPM_S 3000.0f    /* 速度给定斜率限幅 (rpm/s)：0 = 关闭（直接跟随目标）。
                                           α = 3000rpm/s = 314.16rad/s²；加速力矩 J·α
                                           = 3e-6×314.16 ≈ 9.4e-4N·m ≈ 0.026A（Kt=0.0357），
                                           加摩擦 ~0.035A → **斜坡段 iq_ref 预期 ≈0.061A**。
                                           ⚠ 这个预期值只由物理（J、Kt、摩擦）决定、与 kp/ki 无关，
                                             所以它是校验 J 的最好观测量（见 user.c 校验基线）。
                                           ⚠ 3000rpm/s 只有电机能力的 5.3%（Kt·iq_max/J
                                             = 5950rad/s² = 56800rpm/s）⇒ 斜坡段几乎接近稳态：
                                             测摩擦/J 很干净，但**测不出环路动态**
                                             （要看动态把 ramp 设 0 阶跃或提到 20000）。
                                           到 1000rpm 用 0.33s；设得比能力大（>8000）就等于关闭斜坡 */

/* ==================== 角度延迟前推补偿 ====================
 * 电流环/Park 用的电角度其实是"过去某一时刻"的：SSI 上一帧(~3us+最多100us) +
 * 中频环 10kHz 刷新(平均 50us) + PWM 更新生效延迟(0~50us) ⇒ 合计约 100~200us。
 * 转速越高滞后越大：ωe·Δt 在 2343rpm 下 ≈ 14.7°（Δt=150us）。
 * 不补偿的后果：矢量在真实转子上被"掰偏"，转矩少 cos(Δt·ωe)、并被迫输出多余的
 * d 轴电压——实测顶速时 Ud=−0.239 调制比（−1.43V），而理论只需 −ωe·Lq·Iq≈−0.04；
 * 换算 ψf·sin(14°)=1.43V/ωe ⇒ ψf≈0.0034Wb，即偏差确实来自角度滞后（不是对轴：
 * 夹死轴时 Id=0.000 说明零位是准的）。
 * 补偿：θ_used = θ_meas + ωe·Δt。
 * 标定方法：顶速下改这个值，让 ch9(Ud) 最接近 −ωe·Lq·Iq（约 −0.04），即最小 |Ud|。
 * ============================================================ */
#define ENC_ANGLE_LAG_US  150.0f        /* 角度延迟补偿量（us）：0 = 关闭补偿 */

/**
 * @brief 初始化：初始化设备句柄（PWM/位置/电流，写入 handle->device），
 *        重置电流校准累加器（上电自动校准一次）
 * @param handle 共享数据库实例（如全局 mc）
 */
void Control_Init(MC_Handle_t *handle);

/**
 * @brief  设置用户限幅（速度/位置模式的转矩限幅）
 * @param  handle  共享数据库实例（如全局 mc）
 * @param  a       用户要求的最大电流 (A)：钳到 [0, CURRENT_I_MAX_GUARD]
 * @note   写 handle->target.iq_max；速度环每拍按 min(用户限幅, 保底限幅) 限幅 →
 *         改完立即生效。保底限幅（CURRENT_I_MAX_GUARD）在这里钳一次、
 *         在 mc_speed 里再 min() 一次、在电流环里还做一次逐轴钳位（三道都在）
 */
void Control_SetCurrentLimit(MC_Handle_t *handle, float a);

/**
 * @brief 分频调度器（在 20kHz ADC 注入中断中调用）
 * @param handle 共享数据库实例（如全局 mc）
 * @note  传感器信息更新在模式分发之外（任何模式都运行）：
 *        电流更新每拍（20kHz）；位置/角度/速度更新每 CONTROL_MID_DIV 拍（10kHz）；
 *        控制环分发：高频每拍；中频每 CONTROL_MID_DIV 拍（10kHz）；
 *        低频每 CONTROL_LOW_DIV 拍（5kHz）
 */
void Control_Sched(MC_Handle_t *handle);

/**
 * @brief 高频环（20kHz，每拍）：按 handle->mode 分发（停止关断/FOC 待实现；
 *        校准模式无操作——校准已由调度器上电自动完成）
 * @param handle 共享数据库实例（如全局 mc）
 */
void Control_HighLoop(MC_Handle_t *handle);

/**
 * @brief 中频环（10kHz）：按 handle->mode 分发（速度环）
 * @param handle 共享数据库实例（如全局 mc）
 * @note  位置/角度/速度更新在 switch 外（任何模式都运行）；
 *        MODE_SPEED_CURRENT_LOOP / MODE_POS_SPEED_CURRENT_LOOP 在此执行速度环，
 *        输出写入 handle->state.iq_ref 供高频环的电流环使用（**不是 target**：
 *        target 放用户给定，state 放当前真正生效的给定）
 */
void Control_MidLoop(MC_Handle_t *handle);

/**
 * @brief 低频环（5kHz）：按 handle->mode 分发（位置环）
 * @param handle 共享数据库实例（如全局 mc）
 */
void Control_LowLoop(MC_Handle_t *handle);

