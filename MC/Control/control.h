/**
 * @file    control.h
 * @brief   控制层：分频调度 + 三个频率环路（Control 控制层）
 *
 * 职责：
 *  - 所有状态（模式/目标/当前值/设备句柄/调度状态）统一封装在 MC_Handle_t，
 *    Control 函数注入 MC_Handle_t *handle，内部只操作 handle 指向的共享数据；
 *    设备句柄（mc.device）由 Control_Init() 初始化；
 *  - Control_Sched()：20kHz 中断中调用，一个分频调度器——
 *    高频环每拍；中频环每 CONTROL_MID_DIV 拍（2 分频 = 10kHz）；
 *    低频环每 CONTROL_LOW_DIV 拍（4 分频 = 5kHz）。
 *  - 三个频率环路函数内部：先做【传感器信息更新】（switch 外、任何模式都运行，
 *    保证外部始终可读），再按 handle->mode switch 分发控制内容：
 *      Control_HighLoop（20kHz）  电流更新（上电自动校准一次后，每拍一直更新）
 *      Control_MidLoop （10kHz）  位置/角度/速度更新
 *      Control_LowLoop （5kHz）   位置环（待实现）
 *
 * 模式切换：直接写 handle->mode（无独立状态机），停止模式的输出关断
 * 以幂等方式在停止分支每个高频环执行。
 */
